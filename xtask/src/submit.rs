fn k210_submit_makefile() -> &'static str {
    r#"TARGET ?= riscv64imac-unknown-none-elf
PACKAGE ?= tx-kernel-riscv64-m1dock-mock
KERNEL := target/$(TARGET)/release/$(PACKAGE)

.PHONY: all clean check

all: k210.bin

k210.bin:
	cargo build --release -p $(PACKAGE) --target $(TARGET)
	@if command -v rust-objcopy >/dev/null 2>&1; then \
		rust-objcopy -O binary $(KERNEL) k210.bin; \
	elif command -v llvm-objcopy >/dev/null 2>&1; then \
		llvm-objcopy -O binary $(KERNEL) k210.bin; \
	else \
		echo "missing rust-objcopy or llvm-objcopy"; exit 1; \
	fi

check:
	cargo check -p $(PACKAGE) --target $(TARGET)

clean:
	cargo clean
	rm -f k210.bin
"#
}

