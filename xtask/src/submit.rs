fn copy_path(root: &Path, out: &Path, relative_path: &str) -> Result<()> {
    let src = root.join(relative_path);
    let dst = out.join(relative_path);
    if !src.exists() {
        return Err(format!("missing source path {}", src.display()));
    }
    if src.is_dir() {
        copy_dir_contents(&src, &dst)
    } else {
        if let Some(parent) = dst.parent() {
            fs::create_dir_all(parent).map_err(|err| err.to_string())?;
        }
        fs::copy(src, dst).map_err(|err| err.to_string())?;
        Ok(())
    }
}
