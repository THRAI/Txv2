use std::fs;
use std::path::{Path, PathBuf};

use crate::Result;
use crate::util::{copy_dir_contents, optional_option_value, resolve_path};

pub(crate) fn submit(root: &Path, args: Vec<String>) -> Result<()> {
    let Some(kind) = args.first() else {
        return Err("submit command needs `k210`".into());
    };
    match kind.as_str() {
        "k210" => submit_k210(root, &args[1..]),
        other => Err(format!("unknown submit kind '{other}', expected k210")),
    }
}

fn submit_k210(root: &Path, args: &[String]) -> Result<()> {
    let out = optional_option_value(args, "--out")
        .map(PathBuf::from)
        .map(|path| resolve_path(root, path))
        .unwrap_or_else(|| root.join("target").join("submit").join("k210"));
    let dry_run = args.iter().any(|arg| arg == "--dry-run");

    let sources = k210_submit_paths();
    println!("submit k210 -> {}", out.display());
    for path in sources {
        println!("  include {path}");
    }
    if dry_run {
        return Ok(());
    }

    if out.exists() {
        fs::remove_dir_all(&out).map_err(|err| err.to_string())?;
    }
    fs::create_dir_all(&out).map_err(|err| err.to_string())?;

    for path in sources {
        copy_path(root, &out, path)?;
    }
    fs::create_dir_all(out.join(".cargo")).map_err(|err| err.to_string())?;
    if root.join("Cargo.lock").exists() {
        fs::copy(root.join("Cargo.lock"), out.join("Cargo.lock")).map_err(|err| err.to_string())?;
    }

    fs::write(out.join("Cargo.toml"), k210_submit_cargo_toml()).map_err(|err| err.to_string())?;
    fs::write(
        out.join(".cargo").join("config.toml"),
        k210_submit_cargo_config(),
    )
    .map_err(|err| err.to_string())?;
    fs::write(
        out.join("rust-toolchain.toml"),
        k210_submit_rust_toolchain(),
    )
    .map_err(|err| err.to_string())?;
    fs::write(out.join("Makefile"), k210_submit_makefile()).map_err(|err| err.to_string())?;
    fs::write(out.join("README.submit.md"), k210_submit_readme()).map_err(|err| err.to_string())?;
    println!("wrote clean K210 submit tree at {}", out.display());
    println!("next: cd {} && make all", out.display());
    Ok(())
}

